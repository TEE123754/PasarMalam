"""Export the actual FastAPI OpenAPI and generate the initial browser type contract."""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "apps/api"))
from app.main import app  # noqa: E402


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "anyOf" in schema:
        return " | ".join(ts_type(value) for value in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    if kind == "object":
        return "Record<string, unknown>"
    return {
        "integer": "number",
        "number": "number",
        "string": "string",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def export() -> None:
    schema = app.openapi()
    (ROOT / "contracts").mkdir(exist_ok=True)
    (ROOT / "contracts/openapi.json").write_text(
        json.dumps(schema, indent=2) + "\n", encoding="utf-8"
    )
    lines = ["// Generated by scripts/export_contract.py from the API. Do not edit manually."]
    for name, model in schema["components"]["schemas"].items():
        lines.append(f"export interface {name} {{")
        for field, value in model.get("properties", {}).items():
            optional = "" if field in model.get("required", []) else "?"
            lines.append(f"  {field}{optional}: {ts_type(value)}")
        lines.append("}\n")
    (ROOT / "apps/web/src/data/api-contract.ts").write_text("\n".join(lines), encoding="utf-8")
    print("Exported OpenAPI and browser contract.")


if __name__ == "__main__":
    export()
